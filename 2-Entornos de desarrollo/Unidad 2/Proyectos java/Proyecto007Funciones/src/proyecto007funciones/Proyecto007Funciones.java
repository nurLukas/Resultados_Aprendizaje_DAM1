package proyecto007funciones;

public class Proyecto007Funciones {
    static int suma(int operando1,int operando2){
        int suma = operando1 + operando2;
        return suma;
    }

    public static void main(String[] args) {
        System.out.println(suma(3,4));
        
        System.out.println(suma(6,4));
    }
    
}
